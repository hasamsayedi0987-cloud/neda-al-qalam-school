# نسخهٔ ۲.۳.۰ — پلتفرم کامل ارتباطات و پیام‌ها

بخش ارتباطات به‌صورت حرفه‌ای، امن و مطابق وظایف هر نقش توسعه یافت — مدیر کنترل کامل دارد، معلمان و والدین دقیقاً در چارچوب وظایف آموزشی خود ارتباط برقرار می‌کنند و همهٔ محدودیت‌ها **سمت سرور** اعمال می‌شود.

## ۱) صلاحیت‌های ارتباطی — پنل جدید مدیر
- تب جدید «صلاحیت‌ها» در بخش پیام‌ها (تنها مدیر)
- برای **هر نقش** (مدیر، سرمعلم، معلم، والد، شاگرد، کارمند، کتابخانه‌دار): فعال/غیرفعال‌کردن پیام‌رسانی، پیام خصوصی، گروهی، به همهٔ کاربران، اطلاعیهٔ عمومی، پیام فوری، پاسخ، پیوست فایل، رسید خواندن، حذف/ویرایش پیام خود، مودریشن و گزارش
- تعیین نقش‌های مجاز گیرنده برای هر نقش + اجازه‌های ویژهٔ فردی + مسدودسازی فردی
- **رونویسی فردی هر کاربر** — تنظیمات جداگانه برای یک شخص مشخص
- تغییرات **بلافاصله** برای همهٔ کاربران فعال می‌شود و در گزارش فعالیت‌ها ثبت می‌گردد

## ۲) ارسال گروهی هوشمند مدیر
- گیرندگان: همهٔ کاربران، گروه‌های نقشی، صنف‌ها (والدین/شاگردان/معلمان صنف)، افراد مشخص — یا ترکیب همه
- **پیش‌شمارهٔ گیرندگان قبل از ارسال**: «این پیام به ۱۰۳ گیرنده می‌رسد — والدین: ۴۵ …»
- پیام گروهی **بدون تکرار** حتی اگر یک شخص از چند مسیر انتخاب شده باشد

## ۳) رابط آموزشی واقعی معلم ↔ والد (امنیت سمت سرور)
- معلم فقط با والدین/شاگردان **صنف‌های تحت مسئولیت خود** (تدریس + نگرانی) پیام ردوبدل می‌کند
- والد فقط با مدیریت مکتب، **نگران صنف فرزند** و **معلمان صنف فرزند** — بر اساس فرزندان ثبت‌شده
- **چند‌فرزندی**: والد با چند فرزند در صنف‌های مختلف، دسترسی‌اش بر اساس همهٔ فرزندان گسترش می‌یابد (مدیر از پنل «فرزندان سرپرستان» پیوند می‌زند)
- دورزدن رابط کاربری بی‌اثر است — هر درخواست روی سرور با روابط واقعی صنف‌ها و تقسیم مضامین بررسی می‌شود
- اجازهٔ ویژهٔ مدیر: معلم/والد خاص می‌تواند به شخص مشخصی خارج از محدوده‌اش پیام بدهد

## ۴) صندوق پیام‌های حرفه‌ای
- **رسید خواندن**: فرستنده می‌بیند پیام چند نفر از چند نفر خوانده است (در صورت مجاز بودن)
- **گفتگوی دو نفره**: کلیک روی پیام مستقیم = گفتگوی کامل با امکان پاسخ سریع
- جست‌وجو و فیلتر: نخوانده‌ها، نوع (خصوصی/گروهی/همگانی)، نقش فرستنده، صنف، تاریخ
- **پیام فوری** با اعلان پررنگ + **پیوست فایل/عکس** (عکس خودکار فشرده می‌شود)
- **ویرایش پیام خود** تا ۳۰ دقیقه (تا وقتی خوانده نشده) + حذف (دریافتی: برای من؛ خودم: فراخوانی کامل)
- تفکیک بصری پیام‌های خصوصی/گروهی/اطلاعیه‌ها + زمان ارسال شمسی

## ۵) گزارش فعالیت‌ها و مودریشن (مدیر)
- آمار کامل: کل پیام‌ها، رسانی‌ها، خوانده‌شده/نخوانده، انواع، ارسال بر اساس نقش، فرستندگان فعال
- **مودریشن**: بررسی پیام‌های اخیر و حذف کامل پیام نامناسب برای همهٔ گیرندگان
- گزارش فعالیت‌های مدیریتی: تغییر صلاحیت‌ها، حذف پیام نامناسب، پیوند فرزندان

**امنیت و سازگاری**: پیام‌های قدیمی خودکار به ساختار جدید منتقل می‌شوند؛ پشتیبان‌گیری شامل همهٔ دادهٔ جدید (نسخهٔ ۴)؛ حالت آفلاین و همگام‌سازی قبلی کاملاً سالم — پیام آفلاین در صف می‌ماند و پس از اتصال ارسال می‌شود.

**تست**: ۶۲/۶۲ تست جدید (هر ۸ سناریوی الزامی) + رگرسیون کامل ۱۳۳/۱۳۳ + بدون خطای lint و TypeScript

**APK**: نسخهٔ ۲.۳.۰ (versionCode 12) — امضای یکسان با همهٔ نسخه‌های قبلی، نصب مستقیم روی نسخهٔ قدیمی
