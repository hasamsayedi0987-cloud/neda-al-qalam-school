# نسخهٔ ۲.۴.۰ — چت‌خانهٔ مکتب: رابط گفتگوی ساده مثل واتساپ

بخش ارتباطات و پیام‌ها به یک **اپ چت ساده، سریع و زیبا** تبدیل شد — استفاده برای همهٔ کاربران آسان، اما کنترل پیشرفتهٔ مدیر کامل و **بدون نیاز به تغییر کد** حفظ شد. ساختار سایر بخش‌های سالم سیستم دست‌نخورده ماند.

## ۱) فهرست گفتگوها (مثل واتساپ)
- هر گفتگو با **آواتار رنگی نقش**، نام، **آخرین پیام**، زمان هوشمند (امروز = ساعت، غیر از آن = تاریخ شمسی) و **نشان نخوانده**
- جست‌وجوی هم‌زمان گفتگوها و **اشخاص** (شروع گفتگوی جدید مستقیم از جست‌وجو)
- فیلتر سریع «همه / نخوانده‌ها» + دکمهٔ «خواندن همه»

## ۲) صفحهٔ گفتگو با حباب‌های پیام
- حباب پیام من/دیگران، **تاریخ‌بند** (امروز/دیروز/تاریخ)، زمان هر پیام
- **وضعیت خوانده‌شدن**: تیک ارسال ✔ و تیک دوتایی خوانده‌شده ✔✔ (مطابق صلاحیت)
- **ارسال عکس یا فایل** با فشرده‌سازی خودکار عکس (در صورت مجوز از پنل مدیر)
- ویرایش پیام خود تا ۳۰ دقیقه + حذف (خودم: فراخوانی برای همه؛ دریافتی: حذف برای من)
- ارسال با Enter، متن چند‌خطی با Shift+Enter، نوشتار بزرگ‌شونده

## ۳) گفتگوی جدید ساده
- انتخاب مخاطب از فهرست **مجاز** (بر اساس نقش، صنف‌های تدریس/نگرانی و فرزندان ثبت‌شده) با جست‌وجو
- برای مدیر/سرمعلم: تب «گروهی و همگانی» با پنل کامل ارسال گروهی و **پیش‌شمارهٔ گیرندگان** و **بدون تکرار**

## ۴) کانال‌های همگانی/گروهی
- پیام‌های اطلاعیه و گروهی به‌صورت کانال مرتب در همان فهرست — فقط‌خواندنی با دکمهٔ «پیام به فرستنده»
- رسید خواندن گروهی (چند/چند) برای فرستنده

## ۵) سریع و واکنش‌گرا
- **دریافت فوری**: بازآوری خودکار هر ۲۰ ثانیه + با بازگشت به اپ + بلافاصله پس از هر اقدام
- **موبایل**: تک‌صفحه با دکمهٔ بازگشت — **دسکتاپ**: دو‌پنله (فهرست + گفتگو)
- کاملاً **آفلاین‌پسند**: پیام آفلاین با ساعت «در انتظار همگام‌سازی» دیده می‌شود و پس از اتصال خودکار ارسال می‌گردد

## ۶) کنترل کامل مدیر — بدون تغییر کد
- پنل‌های «صلاحیت‌های ارتباطی» و «گزارش فعالیت» از سربرگ چت‌خانه در دسترس مدیر
- همهٔ محدودیت‌ها (محدودهٔ صنف معلم، فرزندان والد، مسدودسازی، اجازه‌های ویژه) همچنان **سمت سرور** اجرا می‌شود — دورزدن رابط بی‌اثر است

